"""Builds src/lib/sanaa-logo.ts: the Sanaa wordmark and the "s." icon mark as
fixed outlines, from Fraunces (opsz 144, wght 380). Run: python3 scripts/sanaa-logo.py
Needs: pip install fonttools brotli"""
import re
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.transformPen import TransformPen

SRC = 'node_modules/@fontsource-variable/fraunces/files/fraunces-latin-full-normal.woff2'
font = instantiateVariableFont(TTFont(SRC), {'opsz': 144, 'wght': 380, 'SOFT': 0, 'WONK': 0})
gs, cmap, xh = font.getGlyphSet(), font.getBestCmap(), font['OS/2'].sxHeight
rnd = lambda d: re.sub(r'-?\d+\.\d+', lambda m: '%.0f' % float(m.group()), d)

def word(text, track=-10):
    pen, bp, x = SVGPathPen(gs), BoundsPen(gs), 0
    for ch in text:
        g = gs[cmap[ord(ch)]]
        g.draw(TransformPen(pen, (1, 0, 0, -1, x, 0))); g.draw(TransformPen(bp, (1, 0, 0, -1, x, 0)))
        x += g.width + track
    return rnd(pen.getCommands()), bp.bounds

def mark(text):
    d, (x0, y0, x1, y1) = word(text)
    r = xh * 0.17
    cx, cy = x1 + r * 1.2, -r
    return d, (x0, y0, cx + r - x0, max(y1, 0) - y0), (cx, cy, r)

wd, wb, wdot = mark('sanaa')
sd, sb, sdot = mark('s')
box = lambda b: '%.0f %.0f %.0f %.0f' % b
dot = lambda c: '{ cx: %.0f, cy: %.0f, r: %.0f }' % c
open('src/lib/sanaa-logo.ts', 'w').write(f'''/**
 * The Sanaa wordmark and icon mark, as fixed outlines: set in Fraunces (optical
 * size 144, weight 380) with the terracotta full stop. Outlines rather than live
 * text, so the logo is identical on every screen, in every school's theme, and
 * never waits for a font. Generated by scripts/sanaa-logo.py — do not edit.
 */
export const SANAA_VIEWBOX = '{box(wb)}';
export const SANAA_WORD = '{wd}';
export const SANAA_DOT = {dot(wdot)};
export const SANAA_S_VIEWBOX = '{box(sb)}';
export const SANAA_S = '{sd}';
export const SANAA_S_DOT = {dot(sdot)};
/** The brand's own colours. Schools' themes never change the Sanaa logo. */
export const SANAA = {{ eucalyptus: '#0b3b34', ivory: '#f6f2ea', terracotta: '#c86a4f' }} as const;
''')
print('ok', box(wb), box(sb))
