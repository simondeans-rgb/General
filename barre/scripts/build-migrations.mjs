/* The .sql files are the source of truth — reviewable, and runnable straight
   through psql. The browser cannot read the filesystem, so this bundles them
   into a TypeScript module. Run automatically before build and test. */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src/lib/db/migrations');
const files = readdirSync(dir).filter(f => f.endsWith('.sql')).sort();

const body = files.map(f => {
  const sql = readFileSync(join(dir, f), 'utf8');
  return `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(sql)} },`;
}).join('\n');

writeFileSync(join(dir, 'generated.ts'),
`// GENERATED by scripts/build-migrations.mjs — do not edit.
// Source of truth is the .sql files alongside this one.
export type Migration = { name: string; sql: string };
export const migrations: Migration[] = [
${body}
];
`);
console.log(`bundled ${files.length} migrations`);
