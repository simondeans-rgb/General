// Writes review/REGISTER.md, a readable version of review/register.json for reviewers.
// Usage: npm run register
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const reg = JSON.parse(readFileSync(join(root, 'review/register.json'), 'utf8'));
const esc = (s) => String(s ?? '—').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const count = (f) => reg.items.filter(f).length;
const order = { high: 0, medium: 1, low: 2 };
const items = [...reg.items].sort((a, b) => order[a.riskTier] - order[b.riskTier] || a.id.localeCompare(b.id, 'en', { numeric: true }));

const out = [
  '# SayWotNow content review register',
  '',
  `Generated from \`review/register.json\` by \`npm run register\`. Do not edit this file by hand.`,
  '',
  `${reg.items.length} items: ${count((i) => i.riskTier === 'high')} high risk, ${count((i) => i.riskTier === 'medium')} medium, ${count((i) => i.riskTier === 'low')} low. ` +
  `${count((i) => i.status === 'approved')} approved, ${count((i) => i.status !== 'approved')} not yet approved.`,
  '',
  '> Qualified HR or employment-law sign-off is a human release gate. Nothing here is approved until a named reviewer records it.',
  '',
  '| ID | Item | Risk | Status | Owner | Reviewer | Reviewed | Next review |',
  '|---|---|---|---|---|---|---|---|',
  ...items.map((i) => `| ${esc(i.id)} | ${esc(i.title)} (${i.kind}) | ${i.riskTier} | ${i.status} | ${esc(i.owner)} | ${esc(i.reviewer)} | ${esc(i.reviewedOn)} | ${esc(i.nextReviewOn)} |`),
  '',
  '## Issues and change log',
  '',
];
for (const i of items) {
  if (!i.issues.length && !i.changeLog.length) continue;
  out.push(`### ${i.id}: ${i.title}`, '', `Jurisdiction: ${i.jurisdiction} · Risk: ${i.riskTier} · Source: ${i.source}`, '');
  for (const s of i.issues) out.push(`- ${s}`);
  for (const c of i.changeLog) out.push(`- **Changed ${c.date}** (${c.by}): ${c.change}`);
  out.push('');
}
writeFileSync(join(root, 'review/REGISTER.md'), out.join('\n'));
console.log(`Wrote review/REGISTER.md (${reg.items.length} items).`);
